package net.fabneo.nfhandshake;

/**
 * 配置模板文本（首次运行时写出，全部带中文注释）。
 *
 * <h2>为什么把模板放在代码里而不是 resources</h2>
 * 模板本身<b>不含任何隐私内容</b>（没有地址、没有密码、没有通道表），
 * 放在代码里可以随 jar 分发而不泄露任何信息。
 * 真正的敏感数据由用户在运行时填写到外部文件。
 */
public final class ConfigTemplates {

	private ConfigTemplates() {
	}

	/** 主配置文件模板（{@code config/nfhandshake.properties}）。 */
	public static final String MAIN = """
			# ============================================================
			# nfhandshake 配置文件（中文注释版）
			# ============================================================
			# 本文件由 mod 首次运行时自动生成。
			# 修改后【重启游戏】生效，不需要重新构建 mod。
			#
			# 重要：本文件包含密码等隐私内容，
			#       请勿提交到 Git / 不要上传到任何云端仓库。
			# ============================================================

			# ---------- 连接设置 ----------
			# 服务器地址，格式 域名:端口
			# 留空表示不自动连接（此时只能手动在游戏里点"多人游戏"进入）
			serverAddress=

			# 启动游戏后是否自动连接上面的 serverAddress
			# true  = 启动后自动连服
			# false = 不自动连接
			autoconnect=false

			# ---------- 自动化操作 ----------
			# 进入服务器后要自动执行的命令（不要带前导斜杠）
			# 例如：server xxx  表示进服后自动执行 /server xxx
			# 留空表示不执行任何命令
			subServerCommand=

			# 是否在收到"请输入 /login"这类提示时自动发送登录命令
			# 需要同时填写下面的 password
			autologin=false

			# 登录密码
			# 留空表示不自动登录
			password=

			# ---------- 握手行为（一般不需要改） ----------
			# 配置阶段回哪个协议段
			#   4 = CONFIGURATION（正确值；服务器在配置阶段协商的就是这一段）
			#   1 = PLAY（错误值，会导致协商失败被服务器拒绝）
			# 保留此项仅为做对照实验，正常请保持 4
			configProto=4

			# PLAY 阶段回哪个协议段（1 = PLAY，正常保持 1）
			playProto=1

			# 对照实验用：只声明前 N 个通道
			#   -1  = 全部通道（正常运行值）
			#   其它 = 只声明前 N 个（用于验证"少一个都不行"）
			channelLimit=-1

			# ---------- 通道表（一般不需要配置） ----------
			# 本 mod 会【自动探测】服务器的通道清单：
			#   服务器在握手时会主动下发它拥有的全部通道，
			#   我们照抄回去即可，因此通常无需手工维护通道表。
			#
			# 仅以下情况才需要外部通道表（可选）：
			#   1. 想离线预置通道内容
			#   2. 做对照实验
			# 外部通道表放在同目录下的：
			#   nfhandshake-channels.json
			# 格式见该文件（若不存在表示使用自动探测模式）。
			""";

	/** 通道表模板（{@code config/nfhandshake-channels.json}）。 */
	public static final String CHANNELS = """
			{
			  "_说明": [
			    "本文件是 NeoForge 通道声明表（服务器模组通道清单）。",
			    "格式：{ \\"模组:通道\\": { \\"version\\": \\"版本\\", \\"flowOrd\\": 0 或 1 } }",
			    "  flowOrd 含义：0 = SERVERBOUND（客户端发往服务端），1 = CLIENTBOUND（服务端发往客户端）",
			    "  flowOrd 可以省略，表示该通道不声明方向",
			    "",
			    "【为什么这个文件在外部】",
			    "  该表本质上是服务器的模组清单，属于敏感信息，",
			    "  因此 mod 本体（jar）不包含它，由用户自行提供。",
			    "",
			    "【怎么得到这张表】",
			    "  方式一：从已成功连接的记录中导出（参考项目内 bot 目录的做法）",
			    "  方式二：向服务器管理员索取",
			    "",
			    "【注意】",
			    "  1. 至少需要覆盖服务端的全部【非 optional】通道，少一个都会协商失败。",
			    "  2. version 必须与服务端完全一致（字符串严格相等）。",
			    "  3. NeoForge 自带的 neoforge:* 通道由 mod 自动补齐，无需在此填写。",
			    "",
			    "下面是示例条目（请替换为真实数据）："
			  ],
			  "example:some_channel": {
			    "version": "1.0.0",
			    "flowOrd": 1
			  },
			  "example:another_channel": {
			    "version": "2.3.1",
			    "flowOrd": 0
			  }
			}
			""";
}
